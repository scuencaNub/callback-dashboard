export function TranslationProvider({ children }: { children: React.ReactNode }) {
        const [locale, setLocale] = useState<Locale>(() => {
                const fromStorage = (typeof window !== 'undefined' && localStorage.getItem('locale')) as Locale | null
                return fromStorage || 'en'
        })

        useEffect(() => {
                if (typeof window !== 'undefined') localStorage.setItem('locale', locale)
        }, [locale])

        const availableLocales = useMemo(() => ([
                { code: 'en', name: 'English' },
                { code: 'es', name: 'Español' },
        ] satisfies { code: Locale, name: string }[]), [])

        const value: TranslationContextType = {
                locale,
                setLocale,
                availableLocales,
        }

        return (
                <TranslationContext.Provider value={value}>
                        <IntlProvider locale={locale} messages={MESSAGES[locale]}>{children}</IntlProvider>
                </TranslationContext.Provider>
        )
}

export function useTranslation() {
        const ctx = useContext(TranslationContext)
        if (!ctx) throw new Error('useTranslation must be used within TranslationProvider')
        return ctx
}
